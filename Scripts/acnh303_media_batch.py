#!/usr/bin/env python3
"""Run validated ACNH L3 media conversion against exact sparse-selected files.

Selection is generated by select_acnh303_shard.py (a stable Git tree hash
partition), not by incomplete REST Contents directory lists. Media errors are
recorded individually and never upgraded to 'converted' on tool exit 0 alone.
"""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import subprocess
import sys

NCA = "e10617820db06889e1638499478da0de_NCA"
TARGET_FORMAT = {"Model": "bfres", "Layout": "bntx", "Sound": "bwav"}
SOURCE_SUFFIX = {"Model": ".zs", "Layout": ".zs", "Sound": ".bwav"}


def write_json(path: Path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def main():
    a = argparse.ArgumentParser(description=__doc__)
    a.add_argument("--root", type=Path, default=Path("."))
    a.add_argument("--selection", type=Path, default=Path("selection.json"))
    a.add_argument("--out", type=Path, default=Path("Unpack_L3_Batch"))
    a.add_argument("--report-dir", type=Path, default=Path("derived/3.0.3/media_batch"))
    a.add_argument("--tool-wmdlt", default="wmdlt")
    a.add_argument("--tool-wimgt", default="wimgt")
    a.add_argument("--tool-vgmstream", default="vgmstream-cli")
    a.add_argument("--fail-on-parser-errors", action="store_true")
    args = a.parse_args()
    root = args.root.resolve()
    selected = json.loads((root / args.selection).read_text(encoding="utf-8"))
    group = selected["category"]
    if group not in TARGET_FORMAT:
        a.error("batch only supports verified Model, Layout and Sound media groups")
    files = selected["paths"]
    if len(files) != selected["selected_files"] or len(files) != len(set(files)):
        a.error("sparse selection JSON has missing or duplicate entries")
    if not selected.get("suffix") or selected["suffix"].lower() != SOURCE_SUFFIX[group]:
        a.error("media shard must explicitly select the correct source format suffix")
    expected_prefix = f"{NCA}/1/{group}/"
    target = TARGET_FORMAT[group]
    results = []
    for num, path in enumerate(files, 1):
        source = (root / path).resolve()
        if (not path.startswith(expected_prefix) or not source.is_relative_to(root)
                or not source.is_file()):
            raise ValueError(f"invalid/missing source path: {path}")
        relative = path[len(f"{NCA}/1/"):]
        blob = source.read_bytes()
        digest = hashlib.sha256(blob).hexdigest()
        cmd = [sys.executable, str(root / "scripts/acnh303_media_l3.py"),
               "--root", str(root), "--source", relative, "--out", str(args.out),
               "--tool-wmdlt", args.tool_wmdlt, "--tool-wimgt", args.tool_wimgt,
               "--tool-vgmstream", args.tool_vgmstream, "--require", target]
        proc = subprocess.run(cmd, cwd=root, text=True, capture_output=True, timeout=240)
        result = {"source_path": relative, "sha256": digest, "source_bytes": len(blob),
                  "decoder_exit_code": proc.returncode, "status": "failed",
                  "format": target, "validated_outputs": [], "parser_errors": []}
        report = root / args.out / NCA / "1" / (relative + ".converted") / "_conversion_manifest.json"
        if report.is_file():
            meta = json.loads(report.read_text(encoding="utf-8"))
            if meta["source_sha256"] != digest:
                raise RuntimeError(f"manifest source SHA-256 mismatch: {relative}")
            model_textures = group == "Model" and any(
                m.get("origin_type") == "texture_only_fres_bntx"
                for m in meta["members"])
            hits = [m for m in meta["members"]
                    if m["status"] == "converted" and (
                        m["format"] == target or
                        (model_textures and m["format"] == "bntx"
                         and m.get("origin_type") == "texture_only_fres_bntx"))]
            result["source_media_class"] = (
                "texture_only_fres_bntx" if model_textures
                else "model_geometry_bfres" if group == "Model"
                else "layout_bntx" if group == "Layout" else "sound_bwav")
            result["validated_outputs"] = [item for m in hits for item in m.get("outputs", [])]
            result["parser_errors"] = [
                {"member": m["source_member"], "error": m["error"]}
                for m in meta["members"] if "error" in m
            ]
            # This is **media conversion coverage**, NOT 'all leaf types converted'.
            if hits:
                result["status"] = "converted_media" if not result["parser_errors"] else "partial_media"
            elif result["parser_errors"]:
                result["status"] = "failed"
            else:
                result["status"] = "no_target_leaf"
            result["all_leaves_converted"] = meta["status"] == "converted"
            result["leaf_count"] = meta["leaf_count"]
        else:
            result["parser_errors"].append({
                "member": relative,
                "error": (proc.stderr + "\n" + proc.stdout)[-1600:] or "no source conversion manifest",
            })
        results.append(result)
        if num % 5 == 0 or num == len(files):
            print(f"{group}: {num}/{len(files)}, {result['status']}, "
                  f"validated_media={sum(len(r['validated_outputs']) for r in results)}",
                  flush=True)

    stats = Counter(item["status"] for item in results)
    report = {
        "group": group, "target_format": target,
        "selected_source_count": selected["selected_files"],
        "actual_source_count": len(results),
        "validated_media_files": sum(len(x["validated_outputs"]) for x in results),
        "validated_media_bytes": sum(o["size_bytes"] for x in results for o in x["validated_outputs"]),
        "status_counts": dict(stats), "shard": selected["shard"],
        "total_shards": selected["shards"], "suffix": selected["suffix"],
        "limits": "Only real decoder outputs with GLB geometry, PNG pixel load, or PCM WAV validation count. No_target_leaf is not an error but is not a conversion.",
    }
    dest = (root / args.report_dir / group / ("%03d-of-%03d" % (selected["shard"], selected["shards"])))
    write_json(dest / "manifest.json", results)
    write_json(dest / "summary.json", report)
    print(json.dumps(report, ensure_ascii=False, indent=2), flush=True)
    if args.fail_on_parser_errors and stats["failed"] != 0:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
