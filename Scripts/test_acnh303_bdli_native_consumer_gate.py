"""BDLI native consumer gate never upgrades static data or alleged GDB logs to proof."""
from __future__ import annotations

import json
import unittest

from acnh303_bdli_native_consumer_gate import gate, validate_capture, OBS_SCHEMA


def event(seq=1, rva=0x100, **overrides):
    row = {
        "schema": OBS_SCHEMA,
        "session_id": "actual-local-gdb-session-1",
        "build_id": "verified-3-0-3-build-id",
        "elf_sha256": "a"*64,
        "sequence": seq, "main_base": 0x100000,
        "rva": rva, "pc": 0x100000 + rva,
        "registers": {f"x{i}": i for i in range(8)},
        "native_runtime_verified": False,
    }
    row.update(overrides)
    return row


class ConsumerEvidenceGateTests(unittest.TestCase):
    def test_without_actual_runtime_log_native_remains_not_captured(self):
        report = gate({
            "source_path": "BDLI/String/CNzh/STR_CategoryName.bdli.zs",
            "source_bytes_and_git_blob_verified_now": True,
        })
        self.assertEqual(report["native_status"], "NOT_CAPTURED")
        self.assertFalse(report["native_runtime_parity_verified"])
        self.assertFalse(report["actual_nintendo_native_consumer_verified"])

    def test_valid_register_records_are_still_unattested(self):
        capture = (json.dumps(event(1)) + "\n" + json.dumps(event(2,0x104)) + "\n").encode()
        out = validate_capture(capture)
        self.assertEqual(out["candidate_anchor_hits"], 2)
        self.assertEqual(out["distinct_candidate_RVAs"], 2)
        self.assertFalse(out["real_BDLI_consumer_call_chain_verified"])
        report = gate({"source_path":"BDLI/test.zs"},capture)
        self.assertEqual(report["native_status"], "CANDIDATE_UNATTESTED")
        self.assertFalse(report["native_runtime_parity_verified"])

    def test_forged_native_success_rejected(self):
        row = event(native_runtime_verified=True)
        with self.assertRaisesRegex(ValueError,"self-proclaimed Native"):
            validate_capture((json.dumps(row)+"\n").encode())

    def test_pc_wrong_build_mixed_session_and_sequences_rejected(self):
        bad = event(pc=0x1234)
        with self.assertRaisesRegex(ValueError,"PC/RVA"):
            validate_capture((json.dumps(bad)+"\n").encode())
        mixed = (json.dumps(event(1)) + "\n" +
                 json.dumps(event(2,session_id="other"))+"\n").encode()
        with self.assertRaisesRegex(ValueError,"mixed GDB sessions"):
            validate_capture(mixed)
        repeated = (json.dumps(event(1))+"\n"+json.dumps(event(1))+"\n").encode()
        with self.assertRaisesRegex(ValueError,"sequence"):
            validate_capture(repeated)

    def test_registers_source_not_autogenerated(self):
        row=event(registers={"x0":0})
        with self.assertRaisesRegex(ValueError,"ARM64 register set"):
            validate_capture((json.dumps(row)+"\n").encode())


if __name__ == "__main__":
    unittest.main()
